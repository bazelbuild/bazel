package com.google.devtools.build.lib.util.regex;

import static com.google.devtools.build.lib.util.StringEncoding.unicodeToInternal;

import com.code_intelligence.jazzer.api.FuzzedDataProvider;
import java.util.function.Predicate;
import java.util.regex.Pattern;
import java.util.regex.PatternSyntaxException;

/**
 * A fuzz test that checks that the optimized regex matcher generated by {@link
 * RegexUtil#asOptimizedMatchingPredicate} behaves just like the original regex matcher.
 */
public class RegexUtilFuzzTest {
  // Bound the time spent per input: java.util.regex can take exponential time in the length of the
  // haystack for the regexes generated by the fuzzer. The original regex is bounded by its number
  // of character accesses below. The optimized matcher can't be bounded directly and may be much
  // slower since it can use find() instead of matches(), which retries at every position, so the
  // haystack has to be kept short.
  private static final int MAX_HAYSTACK_LENGTH = 16;
  private static final int MAX_CHAR_ACCESSES = 1_000_000;

  public static void fuzzerTestOneInput(FuzzedDataProvider data) {
    String needle = data.consumeString(30);
    String haystack = data.consumeString(MAX_HAYSTACK_LENGTH);
    Pattern originalPattern;
    try {
      originalPattern = Pattern.compile(needle, Pattern.DOTALL);
    } catch (PatternSyntaxException e) {
      // The fuzzer generated an invalid regex, skip it.
      return;
    }

    boolean originalMatches;
    try {
      originalMatches =
          originalPattern.matcher(new BoundedCharSequence(haystack, MAX_CHAR_ACCESSES)).matches();
    } catch (BudgetExceededException e) {
      // The original regex backtracks catastrophically on this input, skip it.
      return;
    }
    Predicate<String> optimizedMatcher = RegexUtil.asOptimizedMatchingPredicate(originalPattern);
    boolean optimizedMatches = optimizedMatcher.test(unicodeToInternal(haystack));
    if (originalMatches != optimizedMatches) {
      throw new AssertionError(
"""
Optimized matcher and original matcher differ in behavior:
needle: '%s'
haystack: '%s'
originalPattern.matcher(haystack).matches(): %s
optimizedMatcher.test(haystack): %s
"""
              .formatted(needle, haystack, originalMatches, optimizedMatches));
    }
  }

  private static final class BudgetExceededException extends RuntimeException {
    BudgetExceededException() {
      super(null, null, /* enableSuppression= */ false, /* writableStackTrace= */ false);
    }
  }

  /** A {@link CharSequence} that throws once its characters have been accessed too often. */
  private static final class BoundedCharSequence implements CharSequence {
    private final String delegate;
    private int remainingAccesses;

    BoundedCharSequence(String delegate, int maxAccesses) {
      this.delegate = delegate;
      this.remainingAccesses = maxAccesses;
    }

    @Override
    public char charAt(int index) {
      if (--remainingAccesses < 0) {
        throw new BudgetExceededException();
      }
      return delegate.charAt(index);
    }

    @Override
    public int length() {
      return delegate.length();
    }

    @Override
    public CharSequence subSequence(int start, int end) {
      return new BoundedCharSequence(delegate.substring(start, end), remainingAccesses);
    }

    @Override
    public String toString() {
      return delegate;
    }
  }
}
