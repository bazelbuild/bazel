package com.google.devtools.build.lib.skyframe;

import static com.google.common.base.Preconditions.checkNotNull;

import com.google.common.collect.Interner;
import com.google.devtools.build.lib.cmdline.RepositoryName;
import com.google.devtools.build.lib.concurrent.BlazeInterners;
import com.google.devtools.build.skyframe.SkyFunctionName;
import com.google.devtools.build.skyframe.SkyKey;
import com.google.devtools.build.skyframe.SkyValue;
import java.util.Map;
import java.util.Optional;
import javax.annotation.Nullable;
import net.starlark.java.spelling.SpellChecker;

/**
 * A single fact derived from a repo mapping: the result of one forward lookup, one inverse lookup,
 * or the associated module of a repo.
 *
 * <p>Lookups are keyed by the source of the mapping's entries rather than by the repo using the
 * mapping: either the {@link RepositoryName} of a repo with its own entries or the {@link SkyKey}
 * of entries shared by all repos generated by a module extension.
 *
 * <p>Consumers that depend on these values instead of the full {@link RepositoryMappingValue} are
 * only invalidated if a fact they observed changes.
 */
public sealed interface RepositoryMappingEntryValue extends SkyValue {

  /** The fact as recorded by {@link RepoMappingTracker}. */
  Object payload();

  static ForwardKey forwardKey(Object mappingSource, String apparentName) {
    return ForwardKey.INTERNER.intern(
        new ForwardKey(mappingSource, ForwardKey.NAME_INTERNER.intern(apparentName)));
  }

  static InverseKey inverseKey(Object mappingSource, RepositoryName canonicalName) {
    return InverseKey.INTERNER.intern(new InverseKey(mappingSource, canonicalName));
  }

  static ModuleInfoKey moduleInfoKey(RepositoryName repo) {
    return ModuleInfoKey.INTERNER.intern(new ModuleInfoKey(repo));
  }

  /** Common supertype of all keys. */
  sealed interface Key extends SkyKey {
    @Override
    default SkyFunctionName functionName() {
      return SkyFunctions.REPOSITORY_MAPPING_ENTRY;
    }
  }

  /** Key for the canonical name of {@code apparentName} in the entries of {@code mappingSource}. */
  record ForwardKey(Object mappingSource, String apparentName) implements Key {
    private static final SkyKeyInterner<ForwardKey> INTERNER = SkyKey.newInterner();
    // Apparent names recur across many mapping sources.
    private static final Interner<String> NAME_INTERNER = BlazeInterners.newWeakInterner();

    public ForwardKey {
      checkNotNull(mappingSource);
      checkNotNull(apparentName);
    }

    @Override
    public SkyKeyInterner<ForwardKey> getSkyKeyInterner() {
      return INTERNER;
    }
  }

  /**
   * Key for the first apparent name of {@code canonicalName} in the entries of {@code
   * mappingSource}.
   */
  record InverseKey(Object mappingSource, RepositoryName canonicalName) implements Key {
    private static final SkyKeyInterner<InverseKey> INTERNER = SkyKey.newInterner();

    public InverseKey {
      checkNotNull(mappingSource);
      checkNotNull(canonicalName);
    }

    @Override
    public SkyKeyInterner<InverseKey> getSkyKeyInterner() {
      return INTERNER;
    }
  }

  /** Key for the module associated with {@code repo} and the source of its mapping's entries. */
  record ModuleInfoKey(RepositoryName repo) implements Key {
    private static final SkyKeyInterner<ModuleInfoKey> INTERNER = SkyKey.newInterner();

    public ModuleInfoKey {
      checkNotNull(repo);
    }

    @Override
    public SkyKeyInterner<ModuleInfoKey> getSkyKeyInterner() {
      return INTERNER;
    }
  }

  /**
   * Value for {@link ForwardKey}. The payload is a {@link RepositoryName} or a {@link NotVisible},
   * or null if the mapping source doesn't exist.
   */
  record Forward(@Nullable Object payload) implements RepositoryMappingEntryValue {
    private static final Interner<Forward> INTERNER = BlazeInterners.newWeakInterner();
    static final Forward REPO_NOT_FOUND = new Forward(null);

    static Forward of(Object payload) {
      return INTERNER.intern(new Forward(checkNotNull(payload)));
    }

    /** Returns the payload for looking up {@code apparentName} in {@code entries}. */
    static Object payloadFor(Map<String, RepositoryName> entries, String apparentName) {
      RepositoryName canonicalName = entries.get(apparentName);
      if (canonicalName != null) {
        return canonicalName;
      }
      return new NotVisible(SpellChecker.didYouMean(apparentName, entries.keySet()));
    }

    /**
     * Returns the result of {@link com.google.devtools.build.lib.cmdline.RepositoryMapping#get} for
     * the given payload.
     */
    static RepositoryName toRepositoryName(
        Object payload, String apparentName, RepositoryName contextRepo) {
      if (payload instanceof NotVisible(String didYouMean)) {
        return RepositoryName.createUnvalidated(apparentName).toNonVisible(contextRepo, didYouMean);
      }
      return (RepositoryName) payload;
    }
  }

  /**
   * The payload of a {@link Forward} for a name without an entry. Unlike the {@link RepositoryName}
   * returned by {@link com.google.devtools.build.lib.cmdline.RepositoryMapping#get}, it doesn't
   * depend on the repo performing the lookup.
   */
  record NotVisible(String didYouMean) {
    public NotVisible {
      checkNotNull(didYouMean);
    }
  }

  /** Value for {@link InverseKey}. */
  record Inverse(Optional<String> apparentName) implements RepositoryMappingEntryValue {
    private static final Interner<Inverse> INTERNER = BlazeInterners.newWeakInterner();
    static final Inverse NONE = new Inverse(Optional.empty());

    static Inverse of(Optional<String> apparentName) {
      return apparentName.isEmpty() ? NONE : INTERNER.intern(new Inverse(apparentName));
    }

    @Override
    public Object payload() {
      return apparentName;
    }
  }

  /**
   * Value for {@link ModuleInfoKey}.
   *
   * @param mappingSource the source of the repo mapping's entries as used in {@link ForwardKey} and
   *     {@link InverseKey}, or null if the repo doesn't exist
   */
  record ModuleInfo(
      boolean repoExists,
      Optional<String> associatedModuleName,
      Optional<String> associatedModuleVersion,
      @Nullable String moduleRepoName,
      @Nullable Object mappingSource)
      implements RepositoryMappingEntryValue {
    static final ModuleInfo REPO_NOT_FOUND =
        new ModuleInfo(false, Optional.empty(), Optional.empty(), null, null);

    @Override
    public Object payload() {
      return this;
    }
  }
}
