package com.google.devtools.build.lib.cmdline;

import com.google.common.base.Preconditions;
import com.google.common.collect.ImmutableMap;
import com.google.common.collect.Maps;
import java.util.Map;
import java.util.Map.Entry;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import javax.annotation.Nullable;
import net.starlark.java.spelling.SpellChecker;

/**
 * Stores the mapping from apparent repo name to canonical repo name, from the viewpoint of a
 * context repo.
 *
 * <p>Most repos have an {@link Explicit} mapping that lists all of its entries. Repos generated by
 * module extensions instead have an {@link ExtensionRepositoryMapping}, which resolves the names of
 * the other repos generated by the same extension structurally instead of listing them.
 *
 * <p>This class must not implement {@link net.starlark.java.eval.StarlarkValue} since instances of
 * this class are used as markers by {@link
 * com.google.devtools.build.lib.analysis.starlark.StarlarkCustomCommandLine}.
 */
public abstract sealed class RepositoryMapping
    permits RepositoryMapping.Explicit, ExtensionRepositoryMapping {
  /* An empty repo mapping with the main repo as the context repo. */
  public static final Explicit EMPTY =
      create(ImmutableMap.of("", RepositoryName.MAIN), RepositoryName.MAIN);

  private final RepositoryName contextRepo;

  RepositoryMapping(RepositoryName contextRepo) {
    this.contextRepo = Preconditions.checkNotNull(contextRepo);
  }

  /**
   * The context repo of this repository mapping. It is for providing useful debug information when
   * repository mapping fails due to enforcing strict dependency.
   */
  public final RepositoryName contextRepo() {
    return contextRepo;
  }

  /**
   * Returns the canonical repository name associated with the given apparent repo name. The
   * provided apparent repo name is assumed to be valid.
   */
  public final RepositoryName get(String preMappingName) {
    RepositoryName canonicalRepoName = lookup(preMappingName);
    if (canonicalRepoName != null) {
      return canonicalRepoName;
    }
    return RepositoryName.createUnvalidated(preMappingName)
        .toNonVisible(contextRepo, SpellChecker.didYouMean(preMappingName, knownApparentNames()));
  }

  /**
   * Returns the canonical repository name associated with the given apparent repo name, or null if
   * no repository is visible under that name.
   */
  @Nullable
  abstract RepositoryName lookup(String apparentName);

  /** Returns the apparent names to consider for "did you mean" suggestions. */
  abstract Iterable<String> knownApparentNames();

  /**
   * Returns all entries of this mapping whose canonical repo name is contained in the given set.
   *
   * <p>Unlike {@link Explicit#entries()}, this is supported by all kinds of mappings.
   */
  public abstract ImmutableMap<String, RepositoryName> entriesForRepos(
      Set<String> canonicalRepoNames);

  /**
   * Returns whether this mapping resolves every apparent name to the same canonical name as the
   * given mapping, possibly ignoring differences in the {@link #contextRepo()}.
   *
   * <p>This is meant as a cheap check to share computations between the repos generated by a module
   * extension and may return false for mappings that resolve all names identically.
   */
  public abstract boolean hasSameEntriesAs(RepositoryMapping other);

  /**
   * Returns the first apparent name in this mapping that maps to the given canonical name, if any.
   */
  public abstract Optional<String> getInverse(RepositoryName postMappingName);

  public static Explicit create(
      ImmutableMap<String, RepositoryName> entries, RepositoryName contextRepo) {
    return new Explicit(
        Preconditions.checkNotNull(entries),
        entries.hashCode(),
        Preconditions.checkNotNull(contextRepo),
        /* inverse= */ null);
  }

  /**
   * A repository mapping that explicitly lists all of its entries. This is the case for all repos
   * except those generated by module extensions.
   */
  public static final class Explicit extends RepositoryMapping {
    private final ImmutableMap<String, RepositoryName> entries;
    // entries has an expensive hashCode() method that isn't cached.
    private final int hashCode;
    // Only used to speed up getInverse(), not considered for equality.
    @Nullable private final ImmutableMap<RepositoryName, String> inverse;

    private Explicit(
        ImmutableMap<String, RepositoryName> entries,
        int entriesHashCode,
        RepositoryName contextRepo,
        @Nullable ImmutableMap<RepositoryName, String> inverse) {
      super(contextRepo);
      this.entries = entries;
      this.hashCode = 31 * entriesHashCode + contextRepo.hashCode();
      this.inverse = inverse;
    }

    /** Returns all the entries in this repo mapping. */
    public ImmutableMap<String, RepositoryName> entries() {
      return entries;
    }

    /**
     * Create a new {@link RepositoryMapping} instance based on existing repo mappings and given
     * additional mappings. If there are conflicts, existing mappings will take precedence.
     */
    public Explicit withAdditionalMappings(
        ImmutableMap<String, RepositoryName> additionalMappings) {
      return create(
          ImmutableMap.<String, RepositoryName>builderWithExpectedSize(
                  entries.size() + additionalMappings.size())
              .putAll(additionalMappings)
              .putAll(entries)
              .buildKeepingLast(),
          contextRepo());
    }

    /**
     * Create a new {@link RepositoryMapping} instance based on existing repo mappings and given
     * additional mappings. If there are conflicts, existing mappings will take precedence. The
     * owner repo of the given additional mappings is ignored.
     */
    public Explicit withAdditionalMappings(@Nullable Explicit additionalMappings) {
      return withAdditionalMappings(
          (additionalMappings == null) ? ImmutableMap.of() : additionalMappings.entries);
    }

    /**
     * Returns a new {@link RepositoryMapping} instance with identical contents, except that the
     * inverse mapping is cached, causing {@link #getInverse} to be much more efficient. This is
     * particularly important for the main repo mapping, as it's often used to generate display-form
     * labels ({@link Label#getDisplayForm}).
     */
    public Explicit withCachedInverseMap() {
      var inverse = Maps.<RepositoryName, String>newHashMapWithExpectedSize(entries.size());
      for (Map.Entry<String, RepositoryName> entry : entries.entrySet()) {
        inverse.putIfAbsent(entry.getValue(), entry.getKey());
      }
      return new Explicit(entries, entries.hashCode(), contextRepo(), ImmutableMap.copyOf(inverse));
    }

    @Override
    @Nullable
    RepositoryName lookup(String apparentName) {
      return entries.get(apparentName);
    }

    @Override
    Iterable<String> knownApparentNames() {
      return entries.keySet();
    }

    @Override
    public ImmutableMap<String, RepositoryName> entriesForRepos(Set<String> canonicalRepoNames) {
      return ImmutableMap.copyOf(
          Maps.filterValues(entries, repo -> canonicalRepoNames.contains(repo.getName())));
    }

    @Override
    public boolean hasSameEntriesAs(RepositoryMapping other) {
      // Only compare by identity as this is meant to be cheap.
      return other instanceof Explicit that && entries == that.entries;
    }

    @Override
    public Optional<String> getInverse(RepositoryName postMappingName) {
      if (inverse != null) {
        return Optional.ofNullable(inverse.get(postMappingName));
      }
      return entries.entrySet().stream()
          .filter(e -> e.getValue().equals(postMappingName))
          .map(Entry::getKey)
          .findFirst();
    }

    @Override
    public boolean equals(Object o) {
      return this == o
          || (o instanceof Explicit that
              && hashCode == that.hashCode
              && Objects.equals(entries, that.entries)
              && Objects.equals(contextRepo(), that.contextRepo()));
    }

    @Override
    public int hashCode() {
      return hashCode;
    }

    @Override
    public String toString() {
      return String.format("RepositoryMapping{entries=%s, contextRepo=%s}", entries, contextRepo());
    }
  }
}
