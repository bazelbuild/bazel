/**
 * Computes the module extensions that a build of the given target patterns may evaluate.
 *
 * <p>The traversal runs on the loading-phase graph and thus covers all configurations. It follows
 * all branches of {@code select}s, the default values of late-bound attributes, and the implicit
 * dependencies and toolchain types of aspects and exec groups. A toolchain type only expands the
 * toolchains registered by its owner and the root module, as with {@code
 * --incompatible_restrict_non_root_registrations}. An edge into a repo generated by a module
 * extension marks that extension as in scope, but the traversal doesn't continue into the repo.
 * Instead, it continues with what these repos may reference outside of themselves: the repos that
 * the root module injects into the extension, the labels in the tags of the extension and the
 * references and toolchain types that the extension declares in its metadata.
 */
final class ModTidyScope {
  private static final Label HOST_PLATFORM =
      Label.parseCanonicalUnchecked("@bazel_tools//tools:host_platform");

  private final SkyframeExecutor skyframeExecutor;
  private final ExtendedEventHandler reporter;
  private final int threads;
  private final BazelDepGraphValue depGraph;

  private final Map<SkyKey, SkyValue> values = new HashMap<>();
  private final Set<SkyKey> failedKeys = new HashSet<>();
  private final Set<SkyKey> neededKeys = new LinkedHashSet<>();

  private final Set<ModuleExtensionId> extensions = new LinkedHashSet<>();
  private final Queue<ModuleExtensionId> pendingExtensions = new ArrayDeque<>();
  private final Map<RepositoryName, Optional<ModuleExtensionId>> extensionForRepo = new HashMap<>();

  private final Set<Label> seenTargets = new HashSet<>();
  private final Queue<Label> pendingTargets = new ArrayDeque<>();
  private final Set<Label> seenTypes = new HashSet<>();
  private final Queue<Label> pendingTypes = new ArrayDeque<>();
  private final Set<Label> resolvedTypes = new HashSet<>();
  private final Map<Label, ImmutableSet<Label>> typeResolutions = new HashMap<>();
  private final Set<RepositoryName> seenOwners = new HashSet<>();
  private final Queue<RepositoryName> pendingOwners = new ArrayDeque<>();
  private final Set<TargetPatternValue.TargetPatternKey> pendingToolchainPatterns =
      new LinkedHashSet<>();
  private final Set<TargetPatternValue.TargetPatternKey> pendingTargetPatterns =
      new LinkedHashSet<>();
  private ImmutableList<TargetPatternValue.TargetPatternKey> rootTargetPatterns =
      ImmutableList.of();
  private final Set<Label> candidateToolchains = new LinkedHashSet<>();
  private final Set<Label> followedToolchains = new HashSet<>();

  private TargetPattern.Parser mainRepoParser;
  private boolean changed;

  private ModTidyScope(
      SkyframeExecutor skyframeExecutor,
      ExtendedEventHandler reporter,
      int threads,
      BazelDepGraphValue depGraph) {
    this.skyframeExecutor = skyframeExecutor;
    this.reporter = reporter;
    this.threads = threads;
    this.depGraph = depGraph;
  }

  /**
   * The result of the traversal.
   *
   * @param extensions the extensions used by the root module and those that generate a repo reached
   *     by the traversal
   * @param evaluatedKeys the Skyframe keys evaluated by the traversal
   */
  record Result(ImmutableSet<ModuleExtensionId> extensions, ImmutableSet<SkyKey> evaluatedKeys) {}

  static Result compute(
      SkyframeExecutor skyframeExecutor,
      ExtendedEventHandler reporter,
      int threads,
      BazelDepGraphValue depGraph,
      RepositoryMapping mainRepoMapping,
      ImmutableList<SignedTargetPattern> targetPatterns)
      throws InterruptedException {
    var scope = new ModTidyScope(skyframeExecutor, reporter, threads, depGraph);
    return scope.run(mainRepoMapping, targetPatterns);
  }

  private Result run(
      RepositoryMapping mainRepoMapping, ImmutableList<SignedTargetPattern> targetPatterns)
      throws InterruptedException {
    mainRepoParser =
        new TargetPattern.Parser(PathFragment.EMPTY_FRAGMENT, RepositoryName.MAIN, mainRepoMapping);
    for (ModuleExtensionId extensionId :
        depGraph.getExtensionUsagesTable().column(ModuleKey.ROOT).keySet()) {
      if (!extensionId.isInnate()) {
        addExtension(extensionId);
      }
    }

    rootTargetPatterns =
        ImmutableList.copyOf(TargetPatternValue.keys(targetPatterns, FilteringPolicies.NO_FILTER));
    // The root module's registrations apply to all toolchain types. Execution platforms can only be
    // registered by the root module.
    Module rootModule = depGraph.getDepGraph().get(ModuleKey.ROOT);
    addRegisteredPatterns(
        mainRepoParser,
        rootModule.getToolchainsToRegister(),
        FilteringPolicies.ruleTypeExplicit("toolchain"),
        pendingToolchainPatterns);
    addRegisteredPatterns(
        mainRepoParser,
        rootModule.getExecutionPlatformsToRegister(),
        FilteringPolicies.ruleTypeExplicit("platform"),
        pendingTargetPatterns);
    enqueueTarget(HOST_PLATFORM);

    do {
      changed = false;
      neededKeys.clear();
      processRootTargetPatterns();
      processTargetPatterns();
      processToolchainPatterns();
      processTargets();
      processTypes();
      processOwners();
      processCandidateToolchains();
      processExtensions();
      if (!neededKeys.isEmpty()) {
        evaluate(ImmutableSet.copyOf(neededKeys));
        changed = true;
      }
    } while (changed);

    return new Result(ImmutableSet.copyOf(extensions), ImmutableSet.copyOf(values.keySet()));
  }

  private void evaluate(ImmutableSet<SkyKey> keys) throws InterruptedException {
    EvaluationResult<SkyValue> result =
        skyframeExecutor.evaluate(keys, /* keepGoing= */ true, threads, reporter);
    for (SkyKey key : keys) {
      SkyValue value = result.get(key);
      if (value != null) {
        values.put(key, value);
      } else {
        failedKeys.add(key);
        var errorInfo = result.getError(key);
        if (errorInfo != null && errorInfo.getException() != null) {
          reporter.handle(
              Event.warn(
                  "Ignoring %s while computing the scope: %s"
                      .formatted(key, errorInfo.getException().getMessage())));
        }
      }
    }
  }

  /**
   * Returns the value for the given key, or {@code null} if it hasn't been evaluated yet or failed
   * to evaluate. Use {@link #hasFailed} to tell these cases apart.
   */
  @Nullable
  private SkyValue getValue(SkyKey key) {
    SkyValue value = values.get(key);
    if (value == null && !failedKeys.contains(key)) {
      neededKeys.add(key);
    }
    return value;
  }

  private boolean hasFailed(SkyKey key) {
    return failedKeys.contains(key);
  }

  private void addRegisteredPatterns(
      TargetPattern.Parser parser,
      ImmutableList<String> patterns,
      FilteringPolicy policy,
      Set<TargetPatternValue.TargetPatternKey> into) {
    for (String patternString : patterns) {
      TargetPattern pattern;
      try {
        pattern = parser.parse(patternString);
      } catch (TargetParsingException e) {
        reporter.handle(
            Event.warn(
                "Ignoring invalid registration '%s': %s".formatted(patternString, e.getMessage())));
        continue;
      }
      if (markIfExtensionRepo(pattern.getRepository())) {
        // The repo has to be fetched to determine the registered targets.
        continue;
      }
      if (into.add(
          TargetPatternValue.key(
              SignedTargetPattern.create(pattern, SignedTargetPattern.Sign.POSITIVE), policy))) {
        changed = true;
      }
    }
  }

  /** Returns whether the repo is generated by a module extension that isn't innate. */
  private boolean markIfExtensionRepo(RepositoryName repo) {
    Optional<ModuleExtensionId> extensionId =
        extensionForRepo.computeIfAbsent(
            repo,
            r ->
                r.isMain() || depGraph.getCanonicalRepoNameLookup().containsKey(r)
                    ? Optional.empty()
                    : depGraph.getModuleExtensionForRepo(r).filter(id -> !id.isInnate()));
    if (extensionId.isEmpty()) {
      return false;
    }
    addExtension(extensionId.get());
    return true;
  }

  private void addExtension(ModuleExtensionId extensionId) {
    if (extensions.add(extensionId)) {
      pendingExtensions.add(extensionId);
      changed = true;
    }
  }

  private void processExtensions() {
    Queue<ModuleExtensionId> deferred = new ArrayDeque<>();
    while (!pendingExtensions.isEmpty()) {
      ModuleExtensionId extensionId = pendingExtensions.remove();
      SkyKey usagesKey = SingleExtensionUsagesValue.key(extensionId);
      SkyKey bzlLoadKey = BzlLoadValue.keyForBzlmod(extensionId.bzlFileLabel());
      SkyKey evalKey = SingleExtensionValue.evalKey(extensionId);
      var usages = (SingleExtensionUsagesValue) getValue(usagesKey);
      var bzlLoad = (BzlLoadValue) getValue(bzlLoadKey);
      var result = (SingleExtensionValue) getValue(evalKey);
      if ((usages == null && !hasFailed(usagesKey))
          || (bzlLoad == null && !hasFailed(bzlLoadKey))
          || (result == null && !hasFailed(evalKey))) {
        deferred.add(extensionId);
        continue;
      }

      // Only the root module can inject repos into an extension or override its repos.
      for (RepositoryName repo : depGraph.getRepoOverrides().row(extensionId).values()) {
        if (!markIfExtensionRepo(repo)) {
          addTargetPattern("@@%s//...".formatted(repo.getName()));
        }
      }
      if (usages != null
          && bzlLoad != null
          && bzlLoad.getModule().getGlobal(extensionId.extensionName())
              instanceof ModuleExtension extension) {
        try {
          StarlarkBazelModule.getLabelsInTags(extension, usages).forEach(this::enqueueTarget);
        } catch (ExternalDepsException e) {
          // Reported when the extension is evaluated.
        }
      }
      var metadata =
          result != null ? result.metadata() : Optional.<LockfileModuleExtensionMetadata>empty();
      if (metadata.isPresent()) {
        if (metadata.get().getReferences() != null) {
          metadata.get().getReferences().forEach(this::addTargetPattern);
        }
        if (metadata.get().getToolchainTypes() != null) {
          for (String type : metadata.get().getToolchainTypes()) {
            requestToolchainType(Label.parseCanonicalUnchecked(type));
          }
        }
      }
    }
    pendingExtensions.addAll(deferred);
  }

  private void addTargetPattern(String canonicalPattern) {
    TargetPattern pattern;
    try {
      pattern = mainRepoParser.parse(canonicalPattern);
    } catch (TargetParsingException e) {
      reporter.handle(Event.warn("Ignoring invalid reference: " + e.getMessage()));
      return;
    }
    if (markIfExtensionRepo(pattern.getRepository())) {
      return;
    }
    if (pendingTargetPatterns.add(
        TargetPatternValue.key(
            SignedTargetPattern.create(pattern, SignedTargetPattern.Sign.POSITIVE),
            FilteringPolicies.NO_FILTER))) {
      changed = true;
    }
  }

  private void enqueueTarget(Label label) {
    if (seenTargets.add(label)) {
      pendingTargets.add(label);
      changed = true;
    }
  }

  private void requestToolchainType(Label label) {
    if (seenTypes.add(label)) {
      pendingTypes.add(label);
      changed = true;
    }
  }

  private void processRootTargetPatterns() {
    if (rootTargetPatterns.isEmpty()) {
      return;
    }
    boolean valuesMissing = false;
    for (var key : rootTargetPatterns) {
      if (getValue(key) == null && !hasFailed(key)) {
        valuesMissing = true;
      }
    }
    if (valuesMissing) {
      return;
    }
    var labels = new LinkedHashSet<Label>();
    for (var key : rootTargetPatterns) {
      var value = (TargetPatternValue) values.get(key);
      if (value == null) {
        continue;
      }
      if (key.isNegative()) {
        labels.removeAll(value.getTargets().getTargets());
      } else {
        labels.addAll(value.getTargets().getTargets());
      }
    }
    rootTargetPatterns = ImmutableList.of();
    labels.forEach(this::enqueueTarget);
  }

  private void processTargetPatterns() {
    for (var it = pendingTargetPatterns.iterator(); it.hasNext(); ) {
      var key = it.next();
      var value = (TargetPatternValue) getValue(key);
      if (value == null && !hasFailed(key)) {
        continue;
      }
      it.remove();
      if (value != null) {
        value.getTargets().getTargets().forEach(this::enqueueTarget);
      }
    }
  }

  private void processToolchainPatterns() {
    for (var it = pendingToolchainPatterns.iterator(); it.hasNext(); ) {
      var key = it.next();
      var value = (TargetPatternValue) getValue(key);
      if (value == null && !hasFailed(key)) {
        continue;
      }
      it.remove();
      if (value != null && candidateToolchains.addAll(value.getTargets().getTargets())) {
        changed = true;
      }
    }
  }

  /** Returns the target with the given label, or {@code null} if it isn't available (yet). */
  @Nullable
  private Target getTarget(Label label) {
    PackageIdentifier packageId = label.getPackageIdentifier();
    var packageValue = (PackageValue) getValue(packageId);
    if (packageValue == null) {
      return null;
    }
    try {
      return packageValue.getPackage().getTarget(label.getName());
    } catch (NoSuchTargetException e) {
      return null;
    }
  }

  /** Returns whether the target with the given label can't be loaded at all. */
  private boolean isUnavailable(Label label) {
    return hasFailed(label.getPackageIdentifier())
        || values.containsKey(label.getPackageIdentifier());
  }

  private void processTargets() {
    Queue<Label> deferred = new ArrayDeque<>();
    while (!pendingTargets.isEmpty()) {
      Label label = pendingTargets.remove();
      if (markIfExtensionRepo(label.getRepository())) {
        continue;
      }
      Target target = getTarget(label);
      if (target == null) {
        if (!isUnavailable(label)) {
          deferred.add(label);
        }
        continue;
      }
      visitTarget(target);
    }
    pendingTargets.addAll(deferred);
  }

  private void visitTarget(Target target) {
    if (target instanceof OutputFile outputFile) {
      enqueueTarget(outputFile.getGeneratingRule().getLabel());
      return;
    }
    if (!(target instanceof Rule rule)) {
      return;
    }
    // Visits all branches of selects and the default values of computed and late-bound
    // attributes, but skips nodep attributes such as visibility.
    AggregatingAttributeMapper.of(rule)
        .visitLabels(DependencyFilter.ALL_DEPS, (attribute, label) -> enqueueTarget(label));
    var ruleClass = rule.getRuleClassObject();
    for (ToolchainTypeRequirement type : ruleClass.getToolchainTypes()) {
      requestToolchainType(type.toolchainType());
    }
    for (DeclaredExecGroup execGroup : ruleClass.getDeclaredExecGroups().values()) {
      for (ToolchainTypeRequirement type : execGroup.toolchainTypes()) {
        requestToolchainType(type.toolchainType());
      }
    }
    for (Attribute attribute : rule.getAttributes()) {
      for (Aspect aspect : attribute.getAspects(rule)) {
        AspectDefinition.forEachLabelDepFromAllAttributesOfAspect(
            aspect, DependencyFilter.ALL_DEPS, (aspectAttribute, label) -> enqueueTarget(label));
        for (ToolchainTypeRequirement type : aspect.getDefinition().getToolchainTypes()) {
          requestToolchainType(type.toolchainType());
        }
      }
    }
  }

  /**
   * Resolves aliases to the actual toolchain types, or returns {@code null} if a package still has
   * to be loaded.
   */
  @Nullable
  private ImmutableSet<Label> resolveToolchainType(Label label) {
    ImmutableSet<Label> resolution = typeResolutions.get(label);
    if (resolution != null) {
      return resolution;
    }
    if (markIfExtensionRepo(label.getRepository())) {
      resolution = ImmutableSet.of(label);
    } else {
      Target target = getTarget(label);
      if (target == null) {
        if (!isUnavailable(label)) {
          return null;
        }
        resolution = ImmutableSet.of(label);
      } else if (target instanceof Rule rule && rule.getRuleClass().equals("alias")) {
        var actualLabels = new HashSet<Label>();
        AggregatingAttributeMapper.of(rule).visitLabels("actual", actualLabels::add);
        var builder = ImmutableSet.<Label>builder();
        for (Label actual : actualLabels) {
          ImmutableSet<Label> actualResolution = resolveToolchainType(actual);
          if (actualResolution == null) {
            return null;
          }
          builder.addAll(actualResolution);
        }
        resolution = builder.build();
      } else {
        resolution = ImmutableSet.of(label);
      }
    }
    typeResolutions.put(label, resolution);
    return resolution;
  }

  private void processTypes() {
    Queue<Label> deferred = new ArrayDeque<>();
    while (!pendingTypes.isEmpty()) {
      Label label = pendingTypes.remove();
      ImmutableSet<Label> resolution = resolveToolchainType(label);
      if (resolution == null) {
        deferred.add(label);
        continue;
      }
      enqueueTarget(label);
      for (Label type : resolution) {
        if (resolvedTypes.add(type)) {
          changed = true;
          RepositoryName owner = getOwner(type.getRepository());
          if (seenOwners.add(owner)) {
            pendingOwners.add(owner);
          }
        }
      }
    }
    pendingTypes.addAll(deferred);
  }

  /** Mirrors the ownership rules of toolchain resolution. */
  private RepositoryName getOwner(RepositoryName typeRepo) {
    if (depGraph.getCanonicalRepoNameLookup().containsKey(typeRepo)) {
      return typeRepo;
    }
    return depGraph
        .getModuleExtensionForRepo(typeRepo)
        .map(extensionId -> extensionId.bzlFileLabel().getRepository())
        .orElse(RepositoryName.MAIN);
  }

  private void processOwners() {
    Queue<RepositoryName> deferred = new ArrayDeque<>();
    while (!pendingOwners.isEmpty()) {
      RepositoryName owner = pendingOwners.remove();
      ModuleKey moduleKey = depGraph.getCanonicalRepoNameLookup().get(owner);
      if (owner.isMain() || moduleKey == null) {
        // The root module's registrations have already been added.
        continue;
      }
      ImmutableList<String> registrations =
          depGraph.getDepGraph().get(moduleKey).getToolchainsToRegister();
      if (registrations.isEmpty()) {
        continue;
      }
      SkyKey repoMappingKey = RepositoryMappingValue.key(owner);
      var repoMapping = (RepositoryMappingValue) getValue(repoMappingKey);
      if (repoMapping == null) {
        if (!hasFailed(repoMappingKey)) {
          deferred.add(owner);
        }
        continue;
      }
      addRegisteredPatterns(
          new TargetPattern.Parser(
              PathFragment.EMPTY_FRAGMENT, owner, repoMapping.repositoryMapping()),
          registrations,
          FilteringPolicies.ruleTypeExplicit("toolchain"),
          pendingToolchainPatterns);
    }
    pendingOwners.addAll(deferred);
  }

  private void processCandidateToolchains() {
    for (var it = candidateToolchains.iterator(); it.hasNext(); ) {
      Label label = it.next();
      Target target = getTarget(label);
      if (target == null) {
        if (isUnavailable(label)) {
          it.remove();
        }
        continue;
      }
      if (!(target instanceof Rule rule)) {
        it.remove();
        continue;
      }
      var mapper = AggregatingAttributeMapper.of(rule);
      var typeLabels = new HashSet<Label>();
      mapper.visitLabels("toolchain_type", typeLabels::add);
      boolean matches = false;
      for (Label typeLabel : typeLabels) {
        ImmutableSet<Label> resolution = resolveToolchainType(typeLabel);
        if (resolution != null && resolution.stream().anyMatch(resolvedTypes::contains)) {
          matches = true;
        }
      }
      // Unless it matches, keep the candidate since its type may still be requested later.
      if (matches) {
        // Toolchain resolution analyzes the toolchain target and the target it points to, which
        // is a nodep attribute.
        it.remove();
        if (followedToolchains.add(label)) {
          enqueueTarget(label);
          mapper.visitLabels("toolchain", this::enqueueTarget);
        }
      }
    }
  }
}
