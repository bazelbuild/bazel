package com.google.devtools.build.lib.cmdline;

import com.google.common.base.Preconditions;
import com.google.common.collect.ImmutableMap;
import com.google.common.collect.ImmutableSet;
import com.google.common.collect.Iterables;
import java.util.HashMap;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import javax.annotation.Nullable;

/**
 * The repository mapping of a repo generated by a module extension.
 *
 * <p>Such a repo can see:
 *
 * <ol>
 *   <li>all repos visible from the repo containing the .bzl file that defines the extension (the
 *       <em>host</em>);
 *   <li>all repos generated by the same extension under their internal names, which take precedence
 *       over the host's names;
 *   <li>all repos injected or overridden via {@code inject_repo} or {@code override_repo}, which
 *       take precedence over both of the above.
 * </ol>
 *
 * <p>The canonical name of a repo generated by an extension is always the extension's {@link
 * #repoPrefix()} followed by the repo's internal name, which has to be a valid user-provided repo
 * name and thus can't contain a {@code +}. The mapping relies on this to avoid listing all
 * generated repos: it resolves any apparent name that isn't an override, isn't visible from the
 * host and is a valid internal name to the canonical name the extension would give a repo with that
 * internal name. It only needs to list the internal names that shadow a different repo visible from
 * the host. Since it doesn't know all its entries, it doesn't offer {@link Explicit#entries()}; use
 * {@link #toExplicit} to obtain a mapping that lists them given the full set of generated repos.
 *
 * <p>As a consequence, the mapping usually doesn't change when the extension adds or removes repos,
 * which avoids invalidating all packages and .bzl files in all repos generated by the extension
 * when it does. This comes at the cost of less precise error messages: referencing an apparent name
 * that the extension doesn't generate results in an error about a repository that isn't defined
 * rather than one about a repository that isn't visible.
 *
 * <p>This mapping can't resolve to a repo that wouldn't be visible otherwise: the unique names of
 * module extensions are chosen such that none of them followed by a {@code +} is a prefix of
 * another one, so a canonical name formed by appending a valid internal name to the prefix can only
 * refer to a repo generated by this extension.
 */
public final class ExtensionRepositoryMapping extends RepositoryMapping {

  private final String repoPrefix;
  private final Explicit hostMapping;
  private final ImmutableMap<String, RepositoryName> repoOverrides;

  /** The internal names of generated repos that shadow a different repo visible from the host. */
  private final ImmutableSet<String> shadowingNames;

  private final int hashCode;

  private ExtensionRepositoryMapping(
      RepositoryName contextRepo,
      String repoPrefix,
      Explicit hostMapping,
      ImmutableMap<String, RepositoryName> repoOverrides,
      ImmutableSet<String> shadowingNames) {
    super(contextRepo);
    Preconditions.checkArgument(repoPrefix.endsWith("+"), repoPrefix);
    this.repoPrefix = repoPrefix;
    this.hostMapping = Preconditions.checkNotNull(hostMapping);
    this.repoOverrides = Preconditions.checkNotNull(repoOverrides);
    this.shadowingNames = Preconditions.checkNotNull(shadowingNames);
    this.hashCode =
        Objects.hash(contextRepo, repoPrefix, hostMapping, repoOverrides, shadowingNames);
  }

  /**
   * Creates the mapping for a repo generated by a module extension that resolves the internal names
   * of repos generated by the extension structurally.
   *
   * <p>The result only depends on {@code generatedRepoInternalNames} through the (usually empty)
   * set of internal names that shadow a different repo visible from the host.
   *
   * @param contextRepo the repo generated by the extension
   * @param repoPrefix the unique name of the extension followed by a {@code +}
   * @param hostMapping the mapping of the repo containing the .bzl file that defines the extension
   * @param repoOverrides the repos injected or overridden for this extension, keyed by their
   *     apparent name
   * @param generatedRepoInternalNames the internal names of all repos generated by the extension
   */
  public static ExtensionRepositoryMapping create(
      RepositoryName contextRepo,
      String repoPrefix,
      Explicit hostMapping,
      ImmutableMap<String, RepositoryName> repoOverrides,
      Set<String> generatedRepoInternalNames) {
    var shadowingNames = ImmutableSet.<String>builder();
    // Iterate over the host's entries since there are usually far fewer of them than there are
    // repos generated by the extension.
    for (var entry : hostMapping.entries().entrySet()) {
      String apparentName = entry.getKey();
      if (generatedRepoInternalNames.contains(apparentName)
          && !isGeneratedRepo(repoPrefix, entry.getValue(), apparentName)) {
        shadowingNames.add(apparentName);
      }
    }
    return new ExtensionRepositoryMapping(
        contextRepo, repoPrefix, hostMapping, repoOverrides, shadowingNames.build());
  }

  /**
   * Creates an {@link Explicit} mapping for a repo generated by a module extension that lists all
   * repos generated by the extension and thus resolves exactly the visible repos.
   *
   * <p>See {@link #create} for the meaning of the parameters.
   */
  public static Explicit createExplicit(
      RepositoryName contextRepo,
      String repoPrefix,
      Explicit hostMapping,
      ImmutableMap<String, RepositoryName> repoOverrides,
      Set<String> generatedRepoInternalNames) {
    var entries =
        ImmutableMap.<String, RepositoryName>builderWithExpectedSize(
            hostMapping.entries().size()
                + generatedRepoInternalNames.size()
                + repoOverrides.size());
    entries.putAll(hostMapping.entries());
    for (String internalName : generatedRepoInternalNames) {
      entries.put(internalName, RepositoryName.createUnvalidated(repoPrefix + internalName));
    }
    entries.putAll(repoOverrides);
    return RepositoryMapping.create(entries.buildKeepingLast(), contextRepo);
  }

  /**
   * Returns an {@link Explicit} mapping that resolves all names of existing repos identically to
   * this one, given the internal names of all repos generated by the extension.
   */
  public Explicit toExplicit(Set<String> generatedRepoInternalNames) {
    return createExplicit(
        contextRepo(), repoPrefix, hostMapping, repoOverrides, generatedRepoInternalNames);
  }

  /** The unique name of the extension followed by a {@code +}. */
  public String repoPrefix() {
    return repoPrefix;
  }

  /** The mapping of the repo containing the .bzl file that defines the extension. */
  public Explicit hostMapping() {
    return hostMapping;
  }

  /** The repos injected or overridden for this extension, keyed by their apparent name. */
  public ImmutableMap<String, RepositoryName> repoOverrides() {
    return repoOverrides;
  }

  /**
   * The internal names of repos generated by the extension that shadow a different repo visible
   * from the host.
   */
  public ImmutableSet<String> shadowingNames() {
    return shadowingNames;
  }

  @Override
  @Nullable
  RepositoryName lookup(String apparentName) {
    RepositoryName canonicalName = repoOverrides.get(apparentName);
    if (canonicalName != null) {
      return canonicalName;
    }
    if (shadowingNames.contains(apparentName)) {
      return generatedRepo(apparentName);
    }
    canonicalName = hostMapping.lookup(apparentName);
    if (canonicalName != null) {
      return canonicalName;
    }
    if (isValidInternalName(apparentName)) {
      return generatedRepo(apparentName);
    }
    return null;
  }

  @Override
  Iterable<String> knownApparentNames() {
    return Iterables.concat(
        repoOverrides.keySet(), shadowingNames, hostMapping.knownApparentNames());
  }

  @Override
  public ImmutableMap<String, RepositoryName> entriesForRepos(Set<String> canonicalRepoNames) {
    var result = new HashMap<String, RepositoryName>();
    for (var entry : hostMapping.entriesForRepos(canonicalRepoNames).entrySet()) {
      maybeAddEntry(result, entry.getKey(), entry.getValue());
    }
    for (var entry : repoOverrides.entrySet()) {
      if (canonicalRepoNames.contains(entry.getValue().getName())) {
        maybeAddEntry(result, entry.getKey(), entry.getValue());
      }
    }
    // Covers the shadowing names as well as all other generated repos.
    for (String canonicalRepoName : canonicalRepoNames) {
      if (canonicalRepoName.startsWith(repoPrefix)) {
        String internalName = canonicalRepoName.substring(repoPrefix.length());
        if (isValidInternalName(internalName)) {
          maybeAddEntry(result, internalName, RepositoryName.createUnvalidated(canonicalRepoName));
        }
      }
    }
    return ImmutableMap.copyOf(result);
  }

  /** Adds the entry only if it isn't shadowed by another entry with the same apparent name. */
  private void maybeAddEntry(
      Map<String, RepositoryName> result, String apparentName, RepositoryName canonicalName) {
    if (canonicalName.equals(lookup(apparentName))) {
      result.put(apparentName, canonicalName);
    }
  }

  @Override
  public boolean hasSameEntriesAs(RepositoryMapping other) {
    return other instanceof ExtensionRepositoryMapping that
        && repoPrefix.equals(that.repoPrefix)
        && hostMapping.equals(that.hostMapping)
        && repoOverrides.equals(that.repoOverrides)
        && shadowingNames.equals(that.shadowingNames);
  }

  @Override
  public Optional<String> getInverse(RepositoryName postMappingName) {
    for (var entry : repoOverrides.entrySet()) {
      if (entry.getValue().equals(postMappingName)) {
        return Optional.of(entry.getKey());
      }
    }
    String name = postMappingName.getName();
    if (name.startsWith(repoPrefix)) {
      String internalName = name.substring(repoPrefix.length());
      if (postMappingName.equals(lookup(internalName))) {
        return Optional.of(internalName);
      }
    }
    return hostMapping
        .getInverse(postMappingName)
        .filter(apparentName -> postMappingName.equals(lookup(apparentName)));
  }

  private RepositoryName generatedRepo(String internalName) {
    return RepositoryName.createUnvalidated(repoPrefix + internalName);
  }

  private static boolean isGeneratedRepo(
      String repoPrefix, RepositoryName repo, String internalName) {
    String name = repo.getName();
    return name.length() == repoPrefix.length() + internalName.length()
        && name.startsWith(repoPrefix)
        && name.endsWith(internalName);
  }

  /**
   * Whether the given name is a valid internal name of a repo generated by a module extension, as
   * enforced by {@link RepositoryName#validateUserProvidedRepoName}. In particular, it can't
   * contain a {@code +}, which ensures that the resulting canonical name can't refer to a repo
   * generated by another extension.
   */
  private static boolean isValidInternalName(String name) {
    if (name.isEmpty() || !isAsciiLetterOrDigit(name.charAt(0))) {
      return false;
    }
    for (int i = 1; i < name.length(); i++) {
      char c = name.charAt(i);
      if (!isAsciiLetterOrDigit(c) && c != '-' && c != '.' && c != '_') {
        return false;
      }
    }
    return true;
  }

  private static boolean isAsciiLetterOrDigit(char c) {
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
  }

  @Override
  public boolean equals(Object o) {
    return this == o
        || (o instanceof ExtensionRepositoryMapping that
            && hashCode == that.hashCode
            && contextRepo().equals(that.contextRepo())
            && hasSameEntriesAs(that));
  }

  @Override
  public int hashCode() {
    return hashCode;
  }

  @Override
  public String toString() {
    return String.format(
        "ExtensionRepositoryMapping{contextRepo=%s, repoPrefix=%s, hostMapping=%s,"
            + " repoOverrides=%s, shadowingNames=%s}",
        contextRepo(), repoPrefix, hostMapping, repoOverrides, shadowingNames);
  }
}
