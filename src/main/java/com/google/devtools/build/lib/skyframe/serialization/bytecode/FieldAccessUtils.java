package com.google.devtools.build.lib.skyframe.serialization.bytecode;

import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.lang.reflect.Field;

/**
 * Unreflected {@link MethodHandle} helpers for dynamically generated serialization classes.
 *
 * <p>Adapts raw getter and setter {@link MethodHandle}s via {@link MethodHandle#asType} so that
 * receiver (and non-primitive field) types appear as {@link Object} in generated bytecode.
 *
 * <p>Generated code may only name classes that it can access. When the JVM resolves a class
 * referenced from the generated class's constant pool, for example in a method descriptor or a
 * {@code checkcast}, it throws {@link IllegalAccessError} unless the class is in the same runtime
 * package or is public and in a package exported to the generated class's module. Hidden classes
 * cannot be referenced by name at all. Serialized types often fail these checks: private nested
 * classes, package-private classes in other packages (such as {@code java.util.KeyValueHolder}),
 * and hidden classes. Using {@link Object} in the generated code avoids naming them; the casts to
 * the real types happen inside {@code java.lang.invoke}, using the captured {@link Class} objects.
 */
public final class FieldAccessUtils {

  private static final MethodHandles.Lookup LOOKUP = MethodHandles.lookup();

  /**
   * Returns a getter {@link MethodHandle} for {@code field} adapted to exact signature {@code
   * (Object)returnType}.
   */
  public static MethodHandle unreflectAdaptedGetter(Field field, Class<?> returnType) {
    try {
      field.setAccessible(true);
      return LOOKUP.unreflectGetter(field).asType(MethodType.methodType(returnType, Object.class));
    } catch (IllegalAccessException e) {
      throw new IllegalStateException("Failed to unreflect getter for " + field, e);
    }
  }

  /**
   * Returns a setter {@link MethodHandle} for {@code field} adapted to exact signature {@code
   * (Object, valueType)void}.
   */
  public static MethodHandle unreflectAdaptedSetter(Field field, Class<?> valueType) {
    try {
      field.setAccessible(true);
      return LOOKUP
          .unreflectSetter(field)
          .asType(MethodType.methodType(void.class, Object.class, valueType));
    } catch (IllegalAccessException e) {
      throw new IllegalStateException("Failed to unreflect setter for " + field, e);
    }
  }

  private FieldAccessUtils() {}
}
